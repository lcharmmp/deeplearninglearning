"""
阶段二 · 练习 1b：自动求导（autograd）—— 深度学习的发动机

任务：
    看懂"计算图 + 反向传播"是怎么自动算梯度的。
    训练神经网络全靠它：loss 对每个参数的偏导，都是 backward() 一步算出来的。

运行： python autograd_demo.py
"""

import torch


def main():
    # ------------------------------------------------------------------
    # 1. requires_grad=True 表示"我要这个变量的梯度"
    # ------------------------------------------------------------------
    x = torch.tensor([2.0, 3.0], requires_grad=True)
    print("x =", x.tolist())

    # 构建一个表达式（PyTorch 会悄悄记下计算图）
    y = x ** 2 + 3 * x + 1          # 对每个元素：y_i = x_i^2 + 3*x_i + 1
    print("y = x**2 + 3*x + 1 =", y.tolist())

    # ------------------------------------------------------------------
    # 2. backward()：反向传播。注意：只能对标量调用！
    #    y 是向量，所以先 y.sum() 求和成标量
    #    retain_graph=True：backward 后会释放计算图（省内存）。下面还要对同一张图
    #    再 backward 一次演示链式法则，所以要保留；正常训练中一张图只 backward 一次，
    #    不用写这个参数（记不住没关系，报错了就能想起这一课）。
    # ------------------------------------------------------------------
    y.sum().backward(retain_graph=True)

    # 数学上 d(sum(y))/d(x_i) = 2*x_i + 3，即 x=2 -> 7，x=3 -> 9
    print("x 的梯度:", x.grad.tolist(), "  <- 期望 [7, 9]")

    # ------------------------------------------------------------------
    # 3. 链式法则：梯度会沿计算图一层层乘下来（y 放大 2 倍，梯度也放大 2 倍）
    # ------------------------------------------------------------------
    x.grad.zero_()                  # 梯度会累加（accumulate），用之前要清零！
    z = (y * 2).sum()               # z = 2 * sum(y)
    z.backward()
    print("把 y 放大 2 倍后梯度:", x.grad.tolist(), "  <- 期望 [14, 18]")

    # ------------------------------------------------------------------
    # 4. 不需要梯度的运算：torch.no_grad()（评估模型时用它，省内存、提速）
    # ------------------------------------------------------------------
    with torch.no_grad():
        y_no_grad = x ** 2 + 3 * x + 1
    print("\nno_grad 里算出的张量 requires_grad =", y_no_grad.requires_grad)

    print("\n一句话总结：backward() 帮你把 loss 对每个参数的偏导一次性算好，")
    print("optimizer 拿着这些梯度去更新参数 —— 这就是训练循环的心脏。")


if __name__ == "__main__":
    main()
