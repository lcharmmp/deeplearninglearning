"""
阶段二 · 练习 1a：PyTorch 张量（tensor）基础

任务：
    亲手创建张量、看属性、做运算，把"数据在 PyTorch 里长什么样"混个脸熟。
    对应官方 60 分钟入门教程的第 1 部分。

运行： python tensor_basics.py
"""

import numpy as np
import torch


def main():
    # ------------------------------------------------------------------
    # 1. 创建张量（tensor 就是"多维数组"，和 numpy 的 ndarray 是亲戚）
    # ------------------------------------------------------------------
    a = torch.tensor([[1.0, 2.0], [3.0, 4.0]])   # 从列表直接创建
    z = torch.zeros(2, 3)                         # 全 0
    o = torch.ones(2, 3)                          # 全 1
    r = torch.rand(2, 3)                          # 均匀分布随机数 [0, 1)
    ar = torch.arange(6).reshape(2, 3)            # 0~5 排成 2 行 3 列

    print("a =", a.tolist())
    print("torch.arange(6).reshape(2,3) =", ar.tolist())

    # ------------------------------------------------------------------
    # 2. 查看属性：shape（形状）、dtype（数据类型）、numel（元素个数）
    # ------------------------------------------------------------------
    print("\na 的 shape:", a.shape, "| dtype:", a.dtype, "| 元素个数:", a.numel())

    # ------------------------------------------------------------------
    # 3. 运算：逐元素运算 和 矩阵乘法 要分清（阶段一 numpy 里 @ 和 * 的区别还记得吗）
    # ------------------------------------------------------------------
    print("\na + a =", (a + a).tolist())     # 逐元素相加
    print("a * 2 =", (a * 2).tolist())       # 逐元素乘标量
    print("a @ a =", (a @ a).tolist())       # 矩阵乘法：2x2 @ 2x2
    print("a * a =", (a * a).tolist())       # 逐元素乘法（不是矩阵乘法！结果每个元素是平方）

    # ------------------------------------------------------------------
    # 4. 索引与切片：和 numpy / Python 列表规则一致
    # ------------------------------------------------------------------
    print("\na 的第 0 行:", a[0].tolist())
    print("a 的第 1 列:", a[:, 1].tolist())
    print("a[1, 0] =", a[1, 0].item())       # .item() 把单个元素取成 Python 数字

    # ------------------------------------------------------------------
    # 5. 与 numpy 互转（两者共享内存，改一边另一边也会变，注意别踩坑）
    # ------------------------------------------------------------------
    a_np = a.numpy()
    t_from_np = torch.from_numpy(np.array([1, 2, 3], dtype=np.float32))
    print("\ntorch 转 numpy:", type(a_np).__name__, "| numpy 转 torch:", t_from_np.tolist())

    # ------------------------------------------------------------------
    # 6. 归约运算：sum / mean / max / argmax，后面算 loss、看准确率天天用
    # ------------------------------------------------------------------
    print("\na.sum() =", a.sum().item())
    print("a.mean() =", a.mean().item())
    print("a.max() =", a.max().item(), "| 位置 argmax:", a.argmax().item())

    # ------------------------------------------------------------------
    # 7. 设备：有 NVIDIA 显卡就把张量挪到 GPU，没有就用 CPU（本路线用 CPU 就够）
    # ------------------------------------------------------------------
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print("\n当前设备:", device)
    b = a.to(device)
    print("转移后 b 所在设备:", b.device)


if __name__ == "__main__":
    main()
